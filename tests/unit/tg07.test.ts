import { describe, expect, it } from 'vitest';
import { buildSequences, scoreTrial } from '../../src/modules/tareas/runtime/tg07/sequence.js';
import { calculate, type Trial } from '../../src/modules/evolucion/tg07.js';

const metric = (result: ReturnType<typeof calculate>, code: string, scope = 'SESSION') =>
  result.indicators.find(row => row.metricCode === code && row.scope === scope)!;
function trial(sequence: number[], response = sequence, latency = 1000, total = 2000): Trial {
  return { trial: 1, sequence, valid: true, invalidReason: null, closureReason: response.length < sequence.length ? 'timeout' : 'response',
    responseOpenedAtMs: 10000, responses: response.map((drum, i) => ({ drum, atMs: 10000 + (i ? total : latency) })), earlyTaps: [] };
}
const oracle = () => ({ events: [trial([0, 1]), trial([1, 2], [1, 2], 1200, 2200),
  trial([0, 1, 2], [0, 1, 2], 1400, 2400), trial([0, 1, 2], [1, 0, 2], 1600, 2600)]
  .map((value, index) => ({ ...value, trial: index + 1 })) });

describe('TG-07 reference e213cda / CA-02,04,06,07', () => {
  it('matches every sequence from the fixed original, including practice and reserves', () => {
    // Captured from original buildSequences, not generated by the implementation under test.
    expect(buildSequences()).toEqual({ byLength: {
      2: [[1, 2], [3, 2], [3, 1]], 3: [[0, 1, 0], [3, 2, 0], [0, 2, 0]],
      4: [[0, 3, 2, 0], [0, 3, 1, 3], [2, 3, 2, 3]],
      5: [[1, 3, 1, 0, 1], [1, 3, 2, 3, 1], [0, 1, 2, 1, 3]],
      6: [[3, 0, 1, 2, 1, 3], [2, 3, 0, 1, 0, 3], [0, 1, 0, 1, 3, 0]],
      7: [[1, 3, 0, 1, 0, 3, 1], [0, 3, 0, 1, 3, 1, 2], [0, 1, 3, 1, 3, 1, 3]],
    }, practice: [[2, 1], [2, 0], [1, 0]] });
  });
  it.each([
    [[0, 1, 0], [0, 0, 0], ['correct', 'repetition', 'correct']],
    [[0, 1, 2], [3, 3, 1], ['intrusion', 'repetition', 'order']],
    [[0, 1, 2], [0], ['correct', 'omission', 'omission']],
    [[0, 1], [0, 1, 3], ['correct', 'correct']],
  ])('preserves original scoring priority and extra-tap behavior', (target, taps, positions) => {
    expect(scoreTrial(target as number[], (taps as number[]).map(drum => ({ drum }))).positions).toEqual(positions);
  });
  it('reproduces approved CA-06 arithmetic without trusting a client summary', () => {
    const result = calculate(oracle(), true);
    for (const [code, value] of Object.entries({ accuracy_pct: 75, position_accuracy_pct: 80, delta_precision_pts: -50,
      longest_correct_length: 3, orderErrors: 2, order_error_rate_pct: 20, trials_with_order_errors: 1,
      median_first_tap_latency_ms: 1300, mean_first_tap_latency_ms: 1300, first_tap_latency_sd_ms: 223.6,
      first_tap_latency_cv_pct: 17.2, median_total_response_ms: 2300 })) expect(metric(result, code).value, code).toBe(value);
    expect(metric(result, 'median_first_tap_latency_ms', 'LENGTH_2')).toMatchObject({ value: 1100, sampleSize: 2 });
    expect(metric(result, 'median_first_tap_latency_ms', 'LENGTH_3')).toMatchObject({ value: 1500, sampleSize: 2 });
    expect(result.summary).toMatchObject({ observed: 4, included: 4, totalPositions: 10, status: 'ok' });
  });
  it('excludes invalid and interrupted trials, including unfinished presentation', () => {
    const input = oracle();
    const baseline = calculate(input, true);
    input.events.push({ ...trial([0, 1]), trial: 5, valid: false, invalidReason: 'focus_lost' });
    input.events.push({ ...trial([0, 1], []), trial: 6, closureReason: 'interruption', responseOpenedAtMs: null });
    const result = calculate(input, true);
    expect(metric(result, 'accuracy_pct')).toEqual(metric(baseline, 'accuracy_pct'));
    expect(metric(result, 'median_total_response_ms')).toEqual(metric(baseline, 'median_total_response_ms'));
    expect(result.summary).toMatchObject({ included: 4, excluded: 2 });
  });
  it('distinguishes no data from valid trials with zero correct answers', () => {
    expect(metric(calculate({ events: [] }, true), 'accuracy_pct')).toMatchObject({ value: null, unavailabilityReason: 'NO_VALID_TRIALS' });
    const result = calculate({ events: [trial([0, 1], [])] }, true);
    expect(metric(result, 'accuracy_pct').value).toBe(0);
    expect(metric(result, 'longest_correct_length')).toMatchObject({ value: null, unavailabilityReason: 'NO_CORRECT_TRIALS' });
    expect(metric(result, 'delta_precision_pts').unavailabilityReason).toBe('INSUFFICIENT_LENGTH_DATA');
    expect(result.summary.status).toBe('no_correct_trials');
  });
  it.each([1, 2, 3])('requires three global latencies but one per length: n=%s', n => {
    const result = calculate({ events: Array.from({ length: n }, () => trial([0, 1])) }, true);
    expect(metric(result, 'median_first_tap_latency_ms').value).toBe(n < 3 ? null : 1000);
    expect(metric(result, 'median_first_tap_latency_ms', 'LENGTH_2')).toMatchObject({ value: 1000, sampleSize: n });
  });
  it('excludes incomplete responses from total time, but not first-tap latency', () => {
    const result = calculate({ events: [trial([0, 1]), trial([0, 1]), trial([0, 1], [0])] }, true);
    expect(metric(result, 'median_first_tap_latency_ms').value).toBe(1000);
    expect(metric(result, 'median_total_response_ms')).toMatchObject({ value: null, sampleSize: 2 });
  });
  it('handles zero mean and blocks unapproved methodology', () => {
    const input = { events: [trial([0, 1], [0, 1], 0), trial([0, 1], [0, 1], 0), trial([0, 1], [0, 1], 0)] };
    expect(metric(calculate(input, true), 'first_tap_latency_cv_pct').unavailabilityReason).toBe('ZERO_MEAN_RT');
    expect(calculate(input, false).indicators.every(row => row.value === null && row.unavailabilityReason === 'METHOD_NOT_APPROVED')).toBe(true);
  });
  it('retains extra taps for total response timing without inventing scored positions', () => {
    const result = calculate({ events: [trial([0, 1], [0, 1, 3], 1000, 2500)] }, true);
    expect(result.decisions[0]).toMatchObject({ positionsCorrect: 2, outcome: 'correct', totalResponseMs: 2500 });
  });
  it('rejects non-finite and negative response latencies', () => {
    for (const latency of [-1, NaN, Infinity]) expect(() => calculate({ events: [trial([0, 1], [0, 1], latency)] }, true)).toThrow('INVALID_KUD_DICE_TIMING');
  });
});
